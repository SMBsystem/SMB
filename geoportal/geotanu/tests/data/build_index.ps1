# Rebuilds tests/data/index.js from the test_NN.js files: question count, max points, minutes.
# ASCII only: Windows PowerShell 5.1 reads BOM-less scripts in the ANSI code page.
# Run: powershell -ExecutionPolicy Bypass -File geoportal/geotanu/tests/data/build_index.ps1
$dir = Split-Path -Parent $MyInvocation.MyCommand.Path
$enc = New-Object System.Text.UTF8Encoding($false)
$rows = @()
Get-ChildItem $dir -Filter 'test_*.js' | Sort-Object Name | ForEach-Object {
  $t = [IO.File]::ReadAllText($_.FullName, $enc)
  $m = [regex]::Match($t, 'GEOTANY_TESTS\[(\d+)\]')
  if (-not $m.Success) { return }
  $id = [int]$m.Groups[1].Value
  $single = ([regex]::Matches($t, "type:\s*'single'")).Count
  $multi = ([regex]::Matches($t, "type:\s*'multi'")).Count
  $match = ([regex]::Matches($t, "type:\s*'match'")).Count
  $tm = [regex]::Match($t, 'timeMinutes:\s*(\d+)')
  $time = if ($tm.Success) { [int]$tm.Groups[1].Value } else { 45 }
  $rows += [pscustomobject]@{ id = $id; count = $single + $multi + $match; points = $single + 2 * ($multi + $match); time = $time }
}
$lines = $rows | Sort-Object id | ForEach-Object { "  {0}: {{ count: {1}, points: {2}, time: {3} }}" -f $_.id, $_.count, $_.points, $_.time }
$out = "// UNT variants rebuilt from the originals (tests/data/test_NN.js): id -> questions, max points, minutes.`n" +
  "// Generated by build_index.ps1 - do not edit by hand.`n" +
  "// A variant missing here still opens from the old built-in bank in geotanu.html.`n" +
  "window.GEOTANY_TEST_READY = {`n" + ($lines -join ",`n") + "`n};`n"
[IO.File]::WriteAllText((Join-Path $dir 'index.js'), $out, $enc)
"index.js: " + $rows.Count + " variant(s)"
